//! Installed monthly production and consumption limits at technology zero.
//! Each commodity entry holds its production limit, then its consumption limit.
use crate::{BuildingKind, Commodity};
pub(crate) fn base_limits(kind: BuildingKind) -> &'static [(Commodity, i32, i32)] {
    use BuildingKind::*;
    use Commodity::*;
    match kind {
        PowerLine => &[(HighVoltage, 0, 100)],
        SolarPower => &[(Labor, 0, 5000), (HighVoltage, 90000, 0)],
        Substation => &[(LowVoltage, 300000, 0), (HighVoltage, 0, 150000)],
        ResidenceLowLow => &[
            (Food, 0, 5000),
            (Labor, 3700, 0),
            (Goods, 0, 2400),
            (Waste, 800, 0),
            (LowVoltage, 0, 20500),
            (Water, 0, 5000),
        ],
        OrganicFarm => &[
            (Food, 55000, 0),
            (Labor, 0, 1300),
            (Waste, 0, 600),
            (LowVoltage, 0, 5000),
            (Water, 0, 80000),
        ],
        Market => &[(Labor, 0, 2800), (Waste, 0, 5376000)],
        Track | TrackBridge => &[(Waste, 0, 10000), (LowVoltage, 0, 300)],
        CoalMine => &[(Labor, 0, 91800), (Coal, 100000, 100000)],
        Rail | RailBridge => &[
            (Goods, 0, 7),
            (Steel, 0, 1),
            (Waste, 8, 10000),
            (LowVoltage, 0, 300),
        ],
        CoalPower => &[
            (Labor, 0, 10000),
            (Coal, 0, 4400),
            (HighVoltage, 1100000, 0),
        ],
        Road | RoadBridge => &[(Goods, 0, 4), (Waste, 4, 10000), (LowVoltage, 0, 300)],
        LightIndustry => &[
            (Labor, 0, 5900),
            (Goods, 180000, 0),
            (Ore, 0, 25000),
            (Steel, 0, 1200),
            (LowVoltage, 0, 1800000),
            (HighVoltage, 0, 900000),
        ],
        University => &[(Labor, 0, 25000), (Goods, 0, 75000), (Waste, 25000, 0)],
        Commune => &[
            (Coal, 300, 0),
            (Ore, 700, 0),
            (Steel, 10, 0),
            (Waste, 0, 2000),
            (Water, 0, 8000),
        ],
        OreMine => &[(Labor, 0, 20900), (Ore, 500000, 500000)],
        Tip => &[(Waste, 20000, 20000)],
        Port => &[
            (Food, 500000, 500000),
            (Labor, 0, 10000),
            (Coal, 100000, 100000),
            (Goods, 100000, 100000),
            (Ore, 300000, 300000),
            (Steel, 50000, 50000),
        ],
        HeavyIndustry => &[
            (Labor, 0, 4600),
            (Coal, 0, 7200),
            (Ore, 0, 61200),
            (Steel, 3600, 0),
            (LowVoltage, 0, 720000),
            (HighVoltage, 0, 360000),
        ],
        Parkland | Fire | ParkPond => &[],
        Recycle => &[
            (Labor, 0, 3400),
            (Ore, 5000, 0),
            (Steel, 100, 0),
            (Waste, 0, 55000),
            (LowVoltage, 0, 25000),
        ],
        Health => &[(Labor, 0, 600), (Goods, 0, 4000), (Waste, 1300, 0)],
        RocketPad => &[
            (Labor, 0, 400000),
            (Goods, 0, 20000000),
            (Steel, 0, 480000),
            (Waste, 6666000, 0),
        ],
        Windmill => &[(Labor, 0, 1000), (LowVoltage, 45000, 0)],
        Monument => &[(Labor, 0, 10000)],
        School => &[(Labor, 0, 20000), (Goods, 0, 7500), (Waste, 2500, 0)],
        Blacksmith => &[
            (Labor, 0, 3500),
            (Coal, 0, 100),
            (Goods, 5000, 0),
            (Steel, 0, 100),
        ],
        Mill => &[
            (Food, 0, 3700),
            (Labor, 0, 3500),
            (Coal, 0, 100),
            (Goods, 7500, 0),
            (LowVoltage, 0, 6000),
        ],
        Pottery => &[
            (Labor, 0, 3500),
            (Coal, 0, 200),
            (Goods, 3500, 0),
            (Ore, 0, 1100),
        ],
        FireStation => &[(Labor, 0, 600), (Goods, 0, 300), (Waste, 100, 0)],
        Cricket => &[(Labor, 0, 800), (Goods, 0, 300), (Waste, 100, 0)],
        Shanty => &[
            (Food, 0, 5000),
            (Labor, 0, 500),
            (Coal, 0, 100),
            (Goods, 0, 5000),
            (Ore, 0, 1000),
            (Steel, 0, 100),
            (Waste, 1800, 35300),
        ],
        ResidenceMediumLow | ResidenceLowHigh => &[
            (Food, 0, 10000),
            (Labor, 7400, 0),
            (Goods, 0, 5000),
            (Waste, 1600, 0),
            (LowVoltage, 0, 38000),
            (Water, 0, 10000),
        ],
        ResidenceHighLow | ResidenceMediumHigh => &[
            (Food, 0, 20000),
            (Labor, 14800, 0),
            (Goods, 0, 10000),
            (Waste, 3200, 0),
            (LowVoltage, 0, 73000),
            (Water, 0, 20000),
        ],
        ResidenceHighHigh => &[
            (Food, 0, 40000),
            (Labor, 29600, 0),
            (Goods, 0, 20000),
            (Waste, 6600, 0),
            (LowVoltage, 0, 143000),
            (Water, 0, 40000),
        ],
        Waterwell => &[(Water, 160000, 0)],
        WindPower => &[(Labor, 0, 1500), (HighVoltage, 45000, 0)],
    }
}
